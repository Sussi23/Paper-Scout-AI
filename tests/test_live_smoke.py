"""Live smoke test: real Gemini + OpenAlex. Skipped unless RUN_LIVE=1.

Run:  set RUN_LIVE=1  then  pytest -m live tests/test_live_smoke.py   (PowerShell: $env:RUN_LIVE=1)
"""
import os

import pytest

from backend.agent.research_agent import run_research
from backend.agent.schemas import ResearchRequest
from backend.config import load_settings

pytestmark = [
    pytest.mark.live,
    pytest.mark.skipif(os.environ.get("RUN_LIVE") != "1", reason="set RUN_LIVE=1 to call real APIs"),
]


def test_live_agent_makes_real_tool_calls():
    settings = load_settings(strict=True)
    result = run_research(
        ResearchRequest(topic="adaptive learning systems", year_from=2020, num_papers=2, language="en"),
        settings=settings,
    )
    assert len(result.tool_history) >= 1  # at least one tool call generated by Gemini
    assert (settings.log_dir / f"{result.run_id}.jsonl").is_file()
    assert result.status in {"completed", "partial", "error"}
    assert set(result.selected_ids) <= {s.metadata.paper_id for s in result.selected}
